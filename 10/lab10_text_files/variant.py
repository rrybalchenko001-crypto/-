"""Индивидуальный вариант лабораторной работы №10."""


def selected_sum(matrix: list[list[int]]) -> int:
    """Сумма элементов, удовлетворяющих условию варианта 1.

    Вариант 1: положительные элементы матрицы.
    Индексы строк и столбцов в остальных вариантах задания считаются с нуля.
    """
    return sum(value for row in matrix for value in row if value > 0)
